"""Select exact stock permutations; fail rather than silently substituting shaders."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
variants = json.loads((root / 'TestResults/ShaderSuite/inventory-runtime.json').read_text(encoding='utf-8'))['Variants']
specs = []
def add(source, defines=None, profile=None):
    matches = [v for v in variants if v['Source'] == 'Postprocess/' + source + '.hlsl' and v['Defines'] == (defines or {}) and (profile is None or v['Profile']==profile)]
    assert len(matches) == 1, (source, defines, len(matches))
    specs.append(matches[0])
for source in ['EyeAdaptation/ConstantExposure', 'EyeAdaptation/DownSample', 'EyeAdaptation/EyeAdaptation', 'EyeAdaptation/UpdateHistogram']:
    add(source)
add('EyeAdaptation/UpdateHistogram', {'PRIORITIZE_SCREEN_CENTER': ''})
add('Bloom/PreFilter')
add('Bloom/PreFilter', {'BLOOM_ANTIFLICKER': '1'})
add('Bloom/DownsampleBlur')
add('Bloom/UpsampleBlur')
for extra in [{}, {'FILL_ALPHA_LUMINANCE': ''}, {'DISABLE_TONEMAPPING': ''}, {'DISABLE_TONEMAPPING': '', 'FILL_ALPHA_LUMINANCE': ''}]:
    add('Tonemapping/Main', {'NUMTHREADS': '8', **extra})
add('Fxaa')
add('SSAO/Ssao')
for i in range(1,17):
    add('ChromaticAberration/ChromaticAberration', {'NUMTHREADS': '8', 'ITERATIONS': str(i)})
for axis in ['HORIZONTAL_PASS', 'VERTICAL_PASS']:
    add('Blur', {axis: '', 'MAX_OFFSET': '5', 'DENSITY_FUNCTION': '1'})
for source in ['LinearizeDepth','DeinterleaveDepth','ReconstructNormal']:
    add('HBAO/'+source)
for bits in range(16):
    keys=['ENABLE_BACKGROUND_AO','ENABLE_FOREGROUND_AO','ENABLE_DEPTH_THRESHOLD','FETCH_GBUFFER_NORMAL']
    add('HBAO/CoarseAO',{key:'1' for i,key in enumerate(keys) if bits & (1<<i)},'ps_5_0')
add('HBAO/ReinterleaveAO')
add('HBAO/ReinterleaveAO',{'ENABLE_BLUR':'1'})
for bits in range(4):
    defines={'KERNEL_RADIUS':'4' if bits&1 else '2'}
    if bits&2: defines['ENABLE_SHARPNESS_PROFILE']='1'
    for axis in ['X','Y']: add('HBAO/Blur'+axis,defines)
lines = ['// Generated by scripts/select-postprocess-stages.py from authenticated stock inventory.',
         'namespace ClientPlugin.Rendering.Shaders;', 'public static class PostprocessShaderVariants {',
         'public static readonly string[] Stages = {']
for i, v in enumerate(specs):
    lines.append('"' + v['Id'] + '", // ' + str(i) + ': ' + v['Source'] + ' ' + str(v['Defines']))
lines += ['};', 'public static readonly string[] ShadowBlurs = {']
for axis in ['HORIZONTAL_PASS','VERTICAL_PASS']:
    add('Blur',{axis:'','MAX_OFFSET':'5','DENSITY_FUNCTION':'1','DEPTH_DISCARD_THRESHOLD':'0.1'})
    lines.append('"'+specs[-1]['Id']+'",')
lines += ['};', '}']
(root/'ClientPlugin/Rendering/Shaders/PostprocessShaderVariants.cs').write_text('\n'.join(lines)+'\n', encoding='utf-8')
print('Selected', len(specs), 'stock stages')
