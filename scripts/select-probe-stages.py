"""Use source-captured vertex macros for the stock forward probe pass."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
rows=json.loads((root/'TestResults/ShaderSuite/inventory-runtime.json').read_text(encoding='utf-8'))['Variants']
rigid='POSITION_PACKED;NORMAL;TANGENT_SIGN_OF_BITANGENT;TEXCOORD0_H'
blend='POSITION_PACKED;BLEND_WEIGHTS;BLEND_INDICES;NORMAL;TANGENT_SIGN_OF_BITANGENT;TEXCOORD0_H'
layouts=[rigid,blend,rigid+';GENERIC_INSTANCE',rigid+';CUBE_INSTANCE',blend+';CUBE_INSTANCE']
flags=[None,'USE_SKINNING','USE_GENERIC_INSTANCING','USE_CUBE_INSTANCING','USE_DEFORMED_CUBE_INSTANCING']
specs=[]
for i in range(20):
    kind=i%5;keys={'RENDERING_PASS','TRANSFER_VERTEX_COMPONENTS','VERTEX_COMPONENTS_DECLARATIONS'}
    if flags[kind]:keys.add(flags[kind])
    base=[v for v in rows if v['Source']=='Geometry/Materials/Standard/Vertex.hlsl' and v['VertexLayout']==layouts[kind] and set(v['Defines'])==keys and v['Defines']['RENDERING_PASS']=='0']
    assert len(base)==1
    defines=dict(base[0]['Defines']);defines['RENDERING_PASS']='2'
    if i>=10:defines['METALNESS_COLORABLE']=''
    if (i%10)>=5:defines['ALPHA_MASKED']=''
    specs.append((256+i,'AlphaMasked' if (i%10)>=5 else 'Standard',defines))
for i,variant in enumerate(['a90b2abae7399a4571b7a8ca5fad06b6638baa836f23deb59815759a92207cf0','816f562b63cba18bee1ab58867bfdfc936181c7c7faf56ecebda142584636962']):
    base=next(v for v in rows if v['Id']==variant);defines=dict(base['Defines']);defines['RENDERING_PASS']='2'
    specs.append((276+i,base['Source'].split('/')[-2],defines))
lines=['// Generated by scripts/select-probe-stages.py from authenticated stock inventory.','namespace ClientPlugin.Rendering.Shaders;','public static class ProbeShaderVariants {','public static readonly (uint Id,string Material,System.Collections.Generic.Dictionary<string,string> Defines)[] Extra = {']
for id,material,defines in specs:
    lines.append(f'({id}u,"{material}",new System.Collections.Generic.Dictionary<string,string>{{')
    for key,value in defines.items():lines.append('{'+json.dumps(key)+','+json.dumps(value)+'},')
    lines.append('}),')
lines+=['};','public static readonly string[] Stages = {']
for source in ['EnvPrefiltering','ForwardPostprocess','EnvProbeCopy','EnvProbeBlend']:
    variants=[v for v in rows if v['Source']=='EnvProbe/'+source+'.hlsl' and not v['Defines']];assert len(variants)==1;lines.append('"'+variants[0]['Id']+'",')
lines+=['};','}']
(root/'ClientPlugin/Rendering/Shaders/ProbeShaderVariants.cs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Selected 22 source-backed forward pairs and four stock probe processing stages')
